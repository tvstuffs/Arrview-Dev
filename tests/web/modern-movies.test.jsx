test('Delete… offers Delete and Unmonitor (page stays) and Delete and Remove from Radarr (goes to #/movies) (criterion 25)', async () => {
  const fetchMock = stubFetch({ '/api/radarr/moviefile/': () => reply({}), '/api/radarr/movie/monitor': () => reply({}), '/api/radarr/movie/11': () => reply({}) })
  const toast = vi.fn(); page('11', toast)
  fireEvent.click(await screen.findByRole('button', { name: 'Delete…' }))
  expect(await screen.findByText('Delete movie?')).toBeInTheDocument()
  expect(screen.getByRole('button', { name: 'Delete and Remove from Radarr' })).toBeInTheDocument()
  fireEvent.click(screen.getByRole('button', { name: 'Delete and Unmonitor' }))
  await waitFor(() => expect(toast).toHaveBeenCalledWith('Movie deleted and unmonitored', 'success'))
  expect(requests(fetchMock, 'DELETE')).toEqual([{ url: '/api/radarr/moviefile/5', body: undefined }])
  expect(requests(fetchMock, 'PUT')[0].url).toBe('/api/radarr/movie/monitor')
  await waitFor(() => expect(screen.queryByText('Delete movie?')).toBeNull())
  expect(screen.getByRole('heading', { level: 1, name: 'Movie One' })).toBeInTheDocument()
  window.location.hash = '#/movies/11'
  fireEvent.click(screen.getByRole('button', { name: 'Delete…' }))
  fireEvent.click(await screen.findByRole('button', { name: 'Delete and Remove from Radarr' }))
  await waitFor(() => expect(requests(fetchMock, 'DELETE').map(r => r.url)).toContain('/api/radarr/movie/11?deleteFiles=true'))
  await waitFor(() => expect(window.location.hash).toBe('#/movies'))
})
