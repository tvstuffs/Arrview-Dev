test('movieMeta applies D16/D17: file, unmonitored, release date or status, missing', () => {
  const now = Date.now()
  expect(movieMeta(movies[0], now)).toMatchObject({ text: '2024 · Studio A', attn: false, grey: false })
  expect(movieMeta(movies[1], now)).toMatchObject({ text: 'Missing', attn: true, grey: true })
  expect(movieMeta(movies[2], now).text).toMatch(/^Digital /)
  expect(movieMeta({ ...movies[2], digitalRelease: undefined, physicalRelease: undefined }, now).text).toBe('Announced')
  expect(movieMeta({ ...movies[2], digitalRelease: undefined, physicalRelease: undefined, status: 'inCinemas' }, now).text).toBe('In Cinemas')
  expect(movieMeta({ ...movies[2], digitalRelease: future(60), physicalRelease: future(30) }, now).text).toMatch(/^Physical /)
  expect(movieMeta(movies[3], now)).toMatchObject({ text: 'Unmonitored', attn: false, grey: true })
  expect(movieMeta({ ...movies[1], monitored: false }, now).text).toBe('Unmonitored')
})
